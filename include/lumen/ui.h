// UIEvent::modifiers bits, sampled when the event is dispatched.
enum KeyModifier : std::uint8_t {
    KeyModNone = 0u,
    KeyModCtrl = 1u << 0,
    KeyModShift = 1u << 1,
    KeyModAlt = 1u << 2,
    KeyModSuper = 1u << 3
};

enum class UIEventPhase : std::uint8_t {
    Capture,
    Target,
    Bubble
};

struct UIEvent {
    UIEventType type = UIEventType::PointerMove;
    UIEventPhase phase = UIEventPhase::Target;
    std::uint64_t pointer_id = 0u;
    int button = -1;
    ImGuiKey key = ImGuiKey_None;
    Vec2 position{};
    Vec2 delta{};
    std::uint64_t target_id = 0u;
    std::uint64_t current_target_id = 0u;
    std::uint32_t codepoint = 0u; // TextInput: one Unicode character from the host's text queue
    std::uint8_t modifiers = KeyModNone;
    bool repeat = false;          // KeyDown generated by key auto-repeat
    bool propagation_stopped = false;
    bool default_prevented = false;

    void StopPropagation() noexcept { propagation_stopped = true; }
    void PreventDefault() noexcept { default_prevented = true; }
};

using EventHandler = void (*)(Context* context, UIEvent& event, void* user_data);

